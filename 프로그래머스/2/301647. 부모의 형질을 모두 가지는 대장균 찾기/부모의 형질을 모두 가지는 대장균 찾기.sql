WITH T AS (
    SELECT E.ID
         , E.PARENT_ID
         , E.GENOTYPE
         , P.GENOTYPE P_GENOTYPE
    FROM ECOLI_DATA E
    JOIN ECOLI_DATA P
    ON E.PARENT_ID = P.ID
)

SELECT ID
     , GENOTYPE
     , P_GENOTYPE AS PARENT_GENOTYPE
FROM T
WHERE (GENOTYPE & P_GENOTYPE) = P_GENOTYPE
ORDER BY ID
;