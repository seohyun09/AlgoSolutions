WITH D AS (
    SELECT C.CAR_ID
         , C.CAR_TYPE
         , C.DAILY_FEE
         , H.HISTORY_ID
         , DATEDIFF(H.END_DATE, H.START_DATE) + 1 RENTAL_DATE
    FROM CAR_RENTAL_COMPANY_CAR C
    JOIN CAR_RENTAL_COMPANY_RENTAL_HISTORY H
    ON C.CAR_ID = H.CAR_ID
),

R AS (
    SELECT HISTORY_ID
         , CAR_ID
         , CAR_TYPE
         , DAILY_FEE
         , RENTAL_DATE
         , CASE WHEN RENTAL_DATE >= 90 THEN '90일 이상'
                WHEN RENTAL_DATE >= 30 THEN '30일 이상'
                WHEN RENTAL_DATE >= 7 THEN '7일 이상'
                ELSE '7일 미만'
            END AS DURATION_TYPE
    FROM D
),

T AS (
    SELECT R.HISTORY_ID
         , R.CAR_ID
         , R.CAR_TYPE
         , R.DAILY_FEE
         , R.RENTAL_DATE
         , R.DURATION_TYPE
         , IFNULL(P.DISCOUNT_RATE, 0) AS DISCOUNT_RATE
    FROM R
    LEFT JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN P
   ON R.CAR_TYPE = P.CAR_TYPE AND R.DURATION_TYPE = P.DURATION_TYPE
)

SELECT HISTORY_ID
     , DAILY_FEE * (1 - DISCOUNT_RATE * 0.01) * RENTAL_DATE AS FEE
FROM T
WHERE T.CAR_TYPE = '트럭'
ORDER BY FEE DESC, HISTORY_ID DESC
;